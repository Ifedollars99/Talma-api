import mongoose, { Schema, type HydratedDocument, type Model } from 'mongoose'

export type PaymentStatus = 'pending' | 'paid' | 'failed' | 'abandoned'

/**
 * One attempt by one user to buy one video.
 *
 * Every attempt gets its own Paystack reference. A user is granted access as
 * soon as any of their attempts for that video reaches `paid`; the remaining
 * pending attempts are then abandoned.
 */
export interface VideoPurchaseDocument {
  user: mongoose.Types.ObjectId
  video: mongoose.Types.ObjectId
  /** Set when the video belongs to a creator who receives a revenue share. */
  creator?: mongoose.Types.ObjectId
  creatorSharePercent?: number
  creatorShareKobo?: number
  platformShareKobo?: number
  paystackSubaccountCode?: string
  /** Unique Paystack reference generated by the API. */
  reference: string
  /** Amount in the smallest currency unit at the time of checkout. */
  amountKobo: number
  currency: string
  status: PaymentStatus
  provider: 'paystack'
  providerTransactionId?: number
  providerReference?: string
  channel?: string
  /** Hosted Paystack checkout URL, reused while the pending payment is fresh. */
  authorizationUrl?: string
  /** After this moment the pending checkout is no longer reused. */
  checkoutExpiresAt?: Date
  paidAt?: Date
  createdAt: Date
  updatedAt: Date
}

export type VideoPurchase = HydratedDocument<VideoPurchaseDocument>

const videoPurchaseSchema = new Schema<VideoPurchaseDocument>(
  {
    user: { type: Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    video: { type: Schema.Types.ObjectId, ref: 'Video', required: true, index: true },
    creator: { type: Schema.Types.ObjectId, ref: 'User', index: true },
    creatorSharePercent: { type: Number, min: 0, max: 100 },
    creatorShareKobo: { type: Number, min: 0 },
    platformShareKobo: { type: Number, min: 0 },
    paystackSubaccountCode: { type: String },
    reference: { type: String, required: true, unique: true, index: true },
    amountKobo: { type: Number, required: true, min: 0 },
    currency: { type: String, required: true, default: 'NGN', uppercase: true },
    status: {
      type: String,
      enum: ['pending', 'paid', 'failed', 'abandoned'] as const,
      default: 'pending',
      index: true,
    },
    provider: { type: String, enum: ['paystack'] as const, default: 'paystack' },
    providerTransactionId: { type: Number },
    providerReference: { type: String },
    channel: { type: String },
    authorizationUrl: { type: String },
    checkoutExpiresAt: { type: Date },
    paidAt: { type: Date },
  },
  { timestamps: true, versionKey: false },
)

videoPurchaseSchema.index({ user: 1, video: 1, createdAt: -1 })
videoPurchaseSchema.index({ user: 1, status: 1 })
videoPurchaseSchema.index({ creator: 1, status: 1, createdAt: -1 })

export const VideoPurchaseModel: Model<VideoPurchaseDocument> =
  (mongoose.models.VideoPurchase as Model<VideoPurchaseDocument>) ??
  mongoose.model<VideoPurchaseDocument>('VideoPurchase', videoPurchaseSchema)
